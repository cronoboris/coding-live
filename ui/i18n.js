let lang = 'ko';
let domLang = null; // the language the static HTML was last translated to

export const resolveLanguage = (setting, system) => (setting === 'ko' || setting === 'en' ? setting : /^ko\b/i.test(String(system ?? '')) ? 'ko' : 'en');
export const language = () => lang;

// A key may carry a context after '|' when one Korean word needs two English ones ('일반|이름' shows '일반' in Korean).
export function t(key, vars) {
  const v = lang === 'en' && Object.hasOwn(EN, key) ? EN[key] : key.includes('|') ? key.slice(0, key.indexOf('|')) : key;
  if (typeof v === 'function') return v(vars ?? {});
  return vars ? v.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : v;
}

// Static text in the HTML: elements with data-i18n (their Korean text is the key) and attributes listed in data-i18n-attr.
export function translateDom(root = document) {
  for (const n of root.querySelectorAll('[data-i18n]')) { if (!n.dataset.i18n) n.dataset.i18n = n.textContent.trim(); n.textContent = t(n.dataset.i18n); }
  for (const n of root.querySelectorAll('[data-i18n-attr]')) {
    for (const a of n.dataset.i18nAttr.split(',')) {
      const store = `data-i18n-${a}`;
      if (!n.hasAttribute(store)) n.setAttribute(store, n.getAttribute(a) ?? '');
      n.setAttribute(a, t(n.getAttribute(store)));
    }
  }
}

// Set the language from settings; translates the page when it changes. Returns the language now in use.
export function applyLanguage(settings, system) {
  lang = resolveLanguage(settings?.general?.language ?? 'system', system);
  if (typeof document !== 'undefined' && domLang !== lang) { domLang = lang; document.documentElement.lang = lang; translateDom(); }
  return lang;
}
// For tests and scripts.
export const setLanguage = l => { lang = l === 'en' ? 'en' : 'ko'; };
